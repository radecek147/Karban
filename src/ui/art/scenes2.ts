/** Půllitr s pěnou (pomocník pro hospodské scény). */
function pint(x: number, y: number, s = 1, tilt = 0): SceneOp[] {
  const w = 30 * s;
  const h = 46 * s;
  const tr = (px: number, py: number): string => {
    const a = (tilt * Math.PI) / 180;
    const dx = px - x;
    const dy = py - y;
    return `${(x + dx * Math.cos(a) - dy * Math.sin(a)).toFixed(1)},${(y + dx * Math.sin(a) + dy * Math.cos(a)).toFixed(1)}`;
  };
  return [
    [
      'f',
      'gold',
      `M${tr(x - w / 2, y)} L${tr(x + w / 2, y)} L${tr(x + w / 2 - 3 * s, y + h)} L${tr(x - w / 2 + 3 * s, y + h)} Z`,
      1.8,
    ],
    [
      'f',
      'glass',
      `M${tr(x + w / 2 - 1, y + 8 * s)} C${tr(x + w / 2 + 14 * s, y + 8 * s)} ${tr(x + w / 2 + 14 * s, y + 32 * s)} ${tr(x + w / 2 - 2, y + 32 * s)} L${tr(x + w / 2 - 2, y + 26 * s)} C${tr(x + w / 2 + 7 * s, y + 26 * s)} ${tr(x + w / 2 + 7 * s, y + 14 * s)} ${tr(x + w / 2 - 1, y + 14 * s)} Z`,
      1.4,
    ],
    [
      'f',
      'cloud',
      `M${tr(x - w / 2 - 3 * s, y + 4 * s)} C${tr(x - w / 2 - 6 * s, y - 8 * s)} ${tr(x - 4 * s, y - 12 * s)} ${tr(x, y - 6 * s)} C${tr(x + 6 * s, y - 14 * s)} ${tr(x + w / 2 + 6 * s, y - 8 * s)} ${tr(x + w / 2 + 3 * s, y + 4 * s)} Z`,
      1.6,
    ],
  ];
}

