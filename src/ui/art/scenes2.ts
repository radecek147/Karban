/** Řady šupinek kroužkové košile. */
function mail(x0: number, y0: number, x1: number, y1: number): string {
  let d = '';
  for (let y = y0, row = 0; y < y1; y += 9, row++)
    for (let x = x0 + (row % 2) * 5; x < x1; x += 10) d += `M${x},${y} c2,4 8,4 10,0`;
  return d;
}

