/** Kruh / elipsa jako cesta. */
const c = (cx: number, cy: number, r: number, ry = r): string =>
  `M${cx - r},${cy} A${r},${ry} 0 1,0 ${cx + r},${cy} A${r},${ry} 0 1,0 ${cx - r},${cy} Z`;
/** Obdélník jako cesta. */
const rect = (x: number, y: number, w: number, h: number): string => `M${x},${y} H${x + w} V${y + h} H${x} Z`;
/** Kapka (voda). */
const tear = (x: number, y: number, s = 1): string =>
  `M${x},${y} C${x - 4 * s},${y + 7 * s} ${x - 2.5 * s},${y + 12 * s} ${x},${y + 12 * s} C${x + 2.5 * s},${y + 12 * s} ${x + 4 * s},${y + 7 * s} ${x},${y} Z`;
/** Paprsky / ryska po obvodu kruhu (tahy tuší). */
function ticks(cx: number, cy: number, r1: number, r2: number, n: number): string {
  let d = '';
  for (let i = 0; i < n; i++) {
    const a = (Math.PI * 2 * i) / n;
    const x1 = cx + Math.cos(a) * r1;
    const y1 = cy + Math.sin(a) * r1;
    const x2 = cx + Math.cos(a) * r2;
    const y2 = cy + Math.sin(a) * r2;
    d += `M${x1.toFixed(1)},${y1.toFixed(1)} L${x2.toFixed(1)},${y2.toFixed(1)}`;
  }
  return d;
}
